# %% [markdown]
# # Lesson 10 — Finale: rebuild the whole forward pass from raw weights
#
# You've now seen every part from the outside. Let's throw away the library's
# model code, keep only the **weight tensors**, and write the forward pass
# ourselves in ~60 lines. If our logits match the library's, you have proof
# that you understand *everything* the model does at inference time.
#
# The new bits you haven't seen yet (all small):
# * **RMSNorm** — rescale a vector to a standard size: `x / rms(x) * weight`
# * **RoPE** — position info: rotate pairs of numbers in Q and K by an angle
#   that depends on the token's position. Then `q·k` depends on *distance*.
# * **SwiGLU MLP** — `down( silu(gate(x)) * up(x) )`: expand to 1536, gate, shrink back.

# %%
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd())
from common import *
import torch.nn.functional as F

tok, model, device = load()
cfg = model.config
W = {k: v for k, v in model.state_dict().items()}        # just a dict of tensors now
print(f"{len(W)} weight tensors, e.g.:", list(W)[:3])

# %%
H, KV, D = cfg.num_attention_heads, cfg.num_key_value_heads, cfg.head_dim
EPS, THETA = cfg.rms_norm_eps, cfg.rope_parameters["rope_theta"]

def rms_norm(x, w):
    return x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + EPS) * w

def rope(x, pos):
    """x: (heads, T, D). Rotate first half / second half pairs by position-dependent angles."""
    inv_freq = 1.0 / (THETA ** (torch.arange(0, D, 2, device=x.device).float() / D))  # D/2 speeds
    ang = pos[:, None].float() * inv_freq[None]                    # (T, D/2)
    cos, sin = torch.cat([ang, ang], -1).cos(), torch.cat([ang, ang], -1).sin()
    x1, x2 = x[..., : D // 2], x[..., D // 2:]
    rotated = torch.cat([-x2, x1], -1)
    return x * cos + rotated * sin

def attention(x, p, pos):
    T = x.shape[0]
    q = (x @ W[p + "q_proj.weight"].T).view(T, H, D).transpose(0, 1)     # (H, T, D)
    k = (x @ W[p + "k_proj.weight"].T).view(T, KV, D).transpose(0, 1)    # (KV, T, D)
    v = (x @ W[p + "v_proj.weight"].T).view(T, KV, D).transpose(0, 1)
    q, k = rope(q, pos), rope(k, pos)
    k = k.repeat_interleave(H // KV, dim=0)        # grouped-query: each KV head serves 3 Q heads
    v = v.repeat_interleave(H // KV, dim=0)
    scores = q @ k.transpose(-1, -2) / D ** 0.5                           # (H, T, T)
    mask = torch.triu(torch.ones(T, T, dtype=torch.bool, device=x.device), 1)
    scores = scores.masked_fill(mask, float("-inf"))                      # no peeking ahead
    out = torch.softmax(scores, -1) @ v                                   # (H, T, D)
    out = out.transpose(0, 1).reshape(T, H * D)                           # concat heads
    return out @ W[p + "o_proj.weight"].T

def mlp(x, p):
    gate = F.silu(x @ W[p + "gate_proj.weight"].T)
    up = x @ W[p + "up_proj.weight"].T
    return (gate * up) @ W[p + "down_proj.weight"].T

def my_forward(ids):
    """ids: 1-D tensor of token ids -> logits (T, vocab)."""
    pos = torch.arange(len(ids), device=ids.device)
    x = W["model.embed_tokens.weight"][ids]                               # lesson 04
    for i in range(cfg.num_hidden_layers):                                # lesson 05
        p = f"model.layers.{i}."
        x = x + attention(rms_norm(x, W[p + "input_layernorm.weight"]), p + "self_attn.", pos)
        x = x + mlp(rms_norm(x, W[p + "post_attention_layernorm.weight"]), p + "mlp.")
    x = rms_norm(x, W["model.norm.weight"])
    return x @ W["model.embed_tokens.weight"].T                           # tied lm_head (lesson 05)

# %% [markdown]
# ## Moment of truth

# %%
banner("Our forward pass vs. the library")
ids = encode(tok, "The Eiffel Tower is located in the city of", device)
ours = my_forward(ids[0])
theirs = model(ids).logits[0]
print(f"  max difference in logits: {(ours - theirs).abs().max().item():.2e}")
print(f"  same top-1 prediction at every position? {torch.equal(ours.argmax(-1), theirs.argmax(-1))}")
print(f"  our next token: {tok.decode([ours[-1].argmax().item()])!r}")

# %% [markdown]
# Differences around 1e-4 or smaller are just floating-point rounding
# (operations done in a different order). The model is *exactly* what you wrote.
#
# ## Generate text with nothing but our own code
# Lesson 03's loop + this forward pass = a complete, from-scratch LLM runtime.

# %%
banner("Text generated by our from-scratch implementation")
ids = encode(tok, "Once upon a time, in a quiet village,", device)[0]
for _ in range(30):
    ids = torch.cat([ids, my_forward(ids)[-1].argmax().view(1)])
print(" ", tok.decode(ids))

